--database schema

--units: calories (kcal), protein, fat, carbs (g), per serving.
--safe to run every time the serve starts, only creates tables and indexes that don't exist yet

--every connection must also run "PRAGMA foreign_keys = ON;" because SQLite does not enforce foreign keys
--without turning them on first
PRAGMA foreign_keys = ON;

--LOOKUP TABLES
--COLLATE NOCASE: not case sensitive

CREATE TABLE IF NOT EXISTS INGREDIENTCATEGORY (
    categoryID INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS INGREDIENT (
    ingredientID INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE,
    imageURL TEXT,
    categoryID INTEGER NOT NULL REFERENCES INGREDIENTCATEGORY (categoryID)
);

CREATE TABLE IF NOT EXISTS CUISINE (
    cuisineID INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE
);

CREATE TABLE IF NOT EXISTS DIET (
    dietID INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE
);

CREATE TABLE IF NOT EXISTS FLAVORPROFILE (
    flavorID INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE
);

--RECIPES

--source (where recipe came from): "seed" = from db/recipes.js, "ai" = generated by AI and saved
--createdAt: timestamp UTC filled in automatically when inserted
--name is unique so the same recipe can't be saved twice

CREATE TABLE IF NOT EXISTS RECIPE (
    recipeID INTEGER PRIMARY KEY,
    name TEXT NOT NULL UNIQUE COLLATE NOCASE,
    description TEXT,
    instructions TEXT NOT NULL,
    calories INTEGER NOT NULL CHECK (calories >= 0),
    protein REAL NOT NULL CHECK (protein >= 0),
    fat REAL NOT NULL CHECK (fat >= 0),
    carbs REAL NOT NULL CHECK (carbs >= 0),
    cuisineID INTEGER NOT NULL REFERENCES CUISINE (cuisineID),
    source TEXT NOT NULL DEFAULT 'seed' CHECK (source IN ('seed', 'ai')),
    createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--MANY-TO-MANY TABLES
--CASCADE: deleting a recipe removes its links
--cannot delete an ingredient/diet/flavor if it's still being used by another recipe

CREATE TABLE IF NOT EXISTS RECIPEINGREDIENT (
    recipeID INTEGER NOT NULL REFERENCES RECIPE (recipeID) ON DELETE CASCADE,
    ingredientID INTEGER NOT NULL REFERENCES INGREDIENT (ingredientID),
    quantity REAL CHECK (quantity IS NULL OR quantity > 0),
    unit TEXT,
    PRIMARY KEY (recipeID, ingredientID)
);

CREATE TABLE IF NOT EXISTS RECIPEDIET (
    recipeID INTEGER NOT NULL REFERENCES RECIPE (recipeID) ON DELETE CASCADE,
    dietID INTEGER NOT NULL REFERENCES DIET (dietID),
    PRIMARY KEY (recipeID, dietID)
);

CREATE TABLE IF NOT EXISTS RECIPEFLAVOR (
    recipeID INTEGER NOT NULL REFERENCES RECIPE (recipeID) ON DELETE CASCADE,
    flavorID INTEGER NOT NULL REFERENCES FLAVORPROFILE (flavorID),
    PRIMARY KEY (recipeID, flavorID)
);

--INDEXES
--faster searching for larger databases (:

--looks up the value in a list and goes to the matching ones instead of manually searching through all rows
--finds "recipes that use chicken", etc.

CREATE INDEX IF NOT EXISTS idx_recipeingredient_ingredient ON RECIPEINGREDIENT (ingredientID);
CREATE INDEX IF NOT EXISTS idx_recipediet_diet             ON RECIPEDIET (dietID);
CREATE INDEX IF NOT EXISTS idx_recipeflavor_flavor         ON RECIPEFLAVOR (flavorID);
CREATE INDEX IF NOT EXISTS idx_recipe_cuisine              ON RECIPE (cuisineID);
CREATE INDEX IF NOT EXISTS idx_ingredient_category         ON INGREDIENT (categoryID);
CREATE INDEX IF NOT EXISTS idx_recipe_source               ON RECIPE (source);